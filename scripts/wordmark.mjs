import {readFileSync,writeFileSync} from 'node:fs';
import * as G from '../src/Geometry.res.mjs';
import * as W from '../src/Wordmark.res.mjs';
import {printQuarter} from './palette-analysis.mjs';

export function constructWordmark(source) {
  const r=structuredClone(source);
  r.status='UNKNOWN';
  r.reason='Three oriented image fragments await independent joint display and legal-completion verification.';
  r.sourceDesign='german-short-separator.json';
  r.row4Artwork=[...W.fragments];
  r.palette.separator='wordmark-image-assets';
  r.conventions.symbol='One immutable printed image per physical sticker; only the three branding cells replace single-character separator glyphs.';
  r.conventions.layout='Preferred two-digit hours and space-padded day; row 4 is blank, left/middle/right wordmark fragments, blank.';
  r.proof='docs/WORDMARK.md';
  delete r.reachabilityCertificate;delete r.displayRotationCertificate;
  r.wordmark={name:'CHRONOCUBE / TIME IN MOTION with upward arrow',fragmentOrder:[...W.fragments],targetSlots:[...W.targetSlots],
    allowedQuarterTurns:[0],physicalPieces:'three separate center cubies; never a sticker bridging a cut',
    imageSemantics:'Each token identifies an entire fixed image including all text, arrow, internal colors and pixel arrangement.',
    artworkStatus:'Asset-agnostic feasibility certificate; a production SVG/bitmap split is not generated by this experiment.',
    fragmentStickers:[]};
  for(const s of r.design.stickers) {
    if(s.symbol!=='─')continue;
    const slot=s.targetSlots[0],i=W.targetSlots.indexOf(slot);
    if(i<0||s.targetSlots.length!==1||!['axialCenters','diagonalCenters'].includes(G.orbit(s.position)))throw new Error('Expected dedicated separator center');
    s.symbol=W.fragments[i];s.ink='wordmark-image-assets';
    r.glyphModel.quarterTurns[s.symbol]=[0];
    r.glyphModel.definitions[s.symbol]='distinct immutable upright wordmark image fragment';
    r.wordmark.fragmentStickers.push({id:s.id,fragment:s.symbol,targetSlot:slot,pieceClass:G.orbit(s.position)});
  }
  if(r.wordmark.fragmentStickers.length!==3)throw new Error('Expected three concrete printed image stickers');
  return r;
}
export function generateWordmark() {
  const source=JSON.parse(readFileSync('results/german-short-separator.json','utf8'));
  const result=constructWordmark(source);
  writeFileSync('results/german-wordmark.json',JSON.stringify(result,null,2)+'\n');
  const initial=G.solved(),quote=x=>'"'+String(x).replaceAll('"','""')+'"';
  const csv=['id,face,row,col,image_or_glyph,ink_or_image_asset_group,print_rotation_ccw_degrees,planned_front_slots',...result.design.stickers.map(s=>[s.id,['U','D','F','B','R','L'][Math.floor(s.id/25)],Math.floor(s.id%25/5)+1,s.id%5+1,s.symbol===' '?'BLANK':s.symbol,s.ink,90*printQuarter(initial[s.id],s),s.targetSlots.map(i=>`${Math.floor(i/5)+1}:${i%5+1}`).join('|')].map(quote).join(','))].join('\n')+'\n';
  writeFileSync('results/german-wordmark-printing.csv',csv);
  console.log('Generated fixed three-fragment upright wordmark candidate; no SAT assumed from the unbranded result.');
  return result;
}
if(process.argv[1]?.endsWith('/wordmark.mjs'))generateWordmark();
