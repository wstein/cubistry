/** The six months print D shows with one wrong cell (7,1), the red 29: February, Sunday, 28 days (research: chain-1980-2036/best-effort.tsv). */
const BEST_MONTHS = ["1981-02", "1987-02", "1998-02", "2009-02", "2015-02", "2026-02"];
