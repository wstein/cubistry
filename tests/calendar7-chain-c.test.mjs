// ---- chain structure ----

test("673 states, 672 edges, January 1980 to January 2036, one display per month", () => {
  assert.equal(STATES, 673);
  assert.deepEqual([FIRST, LAST], [{ year: 1980, month: 1 }, { year: 2036, month: 1 }]);
  assert.equal(graph.nodes.length, 673);
  assert.equal(graph.edges.length, 672);
  assert.deepEqual(chainRange(graph), { first: { year: 1980, month: 1 }, last: { year: 2036, month: 1 }, edges: 672 });
  assert.equal(table.months.length, 673);
  assert.equal(table.firstYear, 1980);
  graph.nodes.forEach((n, k) => assert.deepEqual([n.year, n.month, n.display], [ymOf(k).year, ymOf(k).month, k + 1], `node ${k}`));
});

test("the end state of edge i is the start state of edge i+1: one replay, every node hash is reached, every edge starts at the previous node", () => {
  graph.edges.forEach((e, i) => {
    assert.deepEqual([e.from, e.to], [i, i + 1], `edge ${i} joins node ${i} to ${i + 1}`);
    assert.equal(stateDigest(start.printing, poses[i]), graph.nodes[i].hash, `start of edge ${i}`);
    assert.equal(stateDigest(start.printing, applyMoves(poses[i], e.moves)), graph.nodes[i + 1].hash, `end of edge ${i}`);
  });
  assert.equal(stateDigest(start.printing, poses[672]), graph.nodes[672].hash);
});

test("a swapped pair of edge words, a dropped move or a repeated edge breaks the chain at that edge", () => {
  const replayFrom = (k, moves) => stateDigest(start.printing, applyMoves(poses[k], moves));
  assert.notEqual(replayFrom(10, graph.edges[11].moves), graph.nodes[11].hash, "word of edge 11 does not belong to edge 10");
  assert.notEqual(replayFrom(10, graph.edges[10].moves.slice(1)), graph.nodes[11].hash, "dropped first move");
  assert.notEqual(replayFrom(11, graph.edges[10].moves), graph.nodes[12].hash, "edge 10 repeated at node 11");
  assert.throws(() => verifyChain(start.printing, start.pose, table, { nodes: graph.nodes, edges: graph.edges.map((e, i) => (i === 40 ? { ...e, moves: e.moves.slice(1) } : e)) }, best), /edge 40/);
});

// ---- the best-effort months ----

const ymText = (i) => `${ymOf(i).year}-${String(ymOf(i).month).padStart(2, "0")}`;
test("six months are best effort: the front differs from the display in cell (7,1), the red 29, and no other month differs", () => {
  assert.deepEqual(best.map((b) => `${b.year}-${String(b.month).padStart(2, "0")}`), BEST_MONTHS);
  assert.ok(best.every((b) => JSON.stringify(b.wrong) === "[[7,1]]"));
  assert.deepEqual(BEST_EFFORT.map((b) => b.wrong), BEST_MONTHS.map(() => [[7, 1]]));
  const failures = poses.map((p, i) => frontFailures(start.printing, p, table.displays[i].cells));
  failures.forEach((f, i) => { if (!BEST_MONTHS.includes(ymText(i))) assert.equal(f.length, 0, `state ${i} (${ymText(i)}) shows its display`); });
  for (const key of BEST_MONTHS) {
    const k = FIRST_NODE_OF(Number(key.slice(0, 4)), Number(key.slice(5)));
    assert.equal(ymText(k), key);
    assert.equal(failures[k].length, 1, key);
    const [miss] = failures[k];
    assert.deepEqual([miss.row, miss.column], [7, 1], key);
    assert.equal(start.printing.text[miss.sticker - 1], "29", key);
    assert.equal(start.printing.ink[miss.sticker - 1], "red", key);
  }
});

test("each best-effort month is February, a Sunday start and 28 days (derived from Date), and no other month has this configuration", () => {
  const sundayFeb28 = (y, m) => m === 2 && new Date(Date.UTC(y, 1, 1)).getUTCDay() === 0 && new Date(Date.UTC(y, 2, 0)).getUTCDate() === 28;
  const all = Array.from({ length: 673 }, (_, k) => ymText(k)).filter((s) => sundayFeb28(Number(s.slice(0, 4)), Number(s.slice(5))));
  assert.deepEqual(all, BEST_MONTHS);
});

test("verifyChain accepts the chain only with the best-effort entries, and only for exactly that cell", () => {
  assert.equal(verifyChain(start.printing, start.pose, table, graph, best).edges.length, 672);
  assert.throws(() => verifyChain(start.printing, start.pose, table, graph), /edge 12: front differs from display 14 at 7,1/);
  assert.throws(() => verifyChain(start.printing, start.pose, table, graph, best.map((b, i) => (i === 0 ? { ...b, wrong: [[7, 7]] } : b))), /edge 12: the cells that differ .* are \[7,1\], the best-effort entry lists \[7,7\]/);
  assert.throws(() => verifyChain(start.printing, start.pose, table, graph, best.map((b, i) => (i === 0 ? { ...b, wrong: [[7, 1], [7, 7]] } : b))), /edge 12/);
  assert.throws(() => verifyChain(start.printing, start.pose, table, graph, best.map((b, i) => (i === 0 ? { ...b, month: 3 } : b))), /edge 12: front differs from display 14/);
  assert.throws(() => verifyChain(start.printing, start.pose, table, graph, best.slice(1)), /edge 12: front differs from display 14 at 7,1/);
  assert.throws(() => verifyChain(start.printing, start.pose, table, graph, [...best, { year: 1979, month: 12, wrong: [[7, 1]] }]), /not an edge target/);
});

// ---- all 673 displays from the calendar ----

const WEEKDAYS = ["SUN", "MON", "TUE", "WED", "THU", "FRI", "SAT"];
/** The 49 cells (`ink:text`) of a month board from the calendar rules alone: month name in row 1, weekdays in row 2, days from row 3 (six-week months fold the sixth week into week four as d/d+7). */
function boardOf(y, m) {
  const cells = Array.from({ length: 49 }, () => "blank:");
  const set = (r, c, ink, text) => { cells[(r - 1) * 7 + (c - 1)] = `${ink}:${text}`; };
  const off = new Date(Date.UTC(y, m - 1, 1)).getUTCDay(), n = new Date(Date.UTC(y, m, 0)).getUTCDate();
  for (let c = 1; c <= 7; c++) set(2, c, c === 1 || c === 7 ? "red" : "weekday", WEEKDAYS[c - 1]);
  const weeks = Math.floor((off + n - 1) / 7) + 1;
  for (let d = 1; d <= n; d++) {
    const week = Math.floor((off + d - 1) / 7), c = ((off + d - 1) % 7) + 1, ink = c === 1 || c === 7 ? "red" : "dark";
    if (weeks <= 5) set(week + 3, c, ink, String(d));
    else if (week !== 5) set(week + 3, c, ink, week === 4 && d + 7 <= n ? `${d}/${d + 7}` : String(d));
  }
  return cells;
}
test("the display of every one of the 673 months has the weekday header, the days at the weekday of the 1st, and the month name in row 1", () => {
  assert.equal(table.displays.length, 673);
  table.displays.forEach((d, k) => {
    const { year, month } = ymOf(k), want = boardOf(year, month), got = d.cells.map((c) => `${c.ink}:${c.text}`);
    assert.deepEqual([d.year, d.month], [year, month]);
    assert.deepEqual(got.slice(7), want.slice(7), `${year}-${month} rows 2 to 7`);
    const name = new Date(Date.UTC(year, month - 1, 1)).toLocaleString("en-US", { month: "long", timeZone: "UTC" }).toUpperCase();
    assert.equal(d.cells.slice(0, 7).map((c) => c.text).join(""), name, `${year}-${month} row 1 spells the month`);
    d.cells.slice(0, 7).forEach((c) => assert.equal(c.ink, c.text ? "month" : "band"));
  });
  // The independent board is sensitive: a wrong weekday offset or month length differs.
  assert.notDeepEqual(boardOf(2019, 1), boardOf(2019, 2));
  assert.notDeepEqual(boardOf(2024, 2), boardOf(2023, 2));
});

// ---- acceptance: the root month 1980-01 is the solved cube, front face white in Rubik-Tint ----

/** Home position of piece p (1..218): the p-th cell of the 7x7x7 surface in x, y, z order (x slowest), independent of the data. */
const surface = (() => {
  const out = [];
  for (let x = -3; x <= 3; x++) for (let y = -3; y <= 3; y++) for (let z = -3; z <= 3; z++) if (Math.max(Math.abs(x), Math.abs(y), Math.abs(z)) === 3) out.push([x, y, z]);
  return out;
})();
/**
 * Why a pose is not the solved cube of this print (empty: solved): a sticker off its piece's home cell, not on an outer face of
 * it, or on another face than its number says (the stickers of a piece are numbered in the order of the x, y, z faces).
 */
function unsolved(printing, pose) {
  const why = [];
  let lastPiece = 0, lastAxis = -1;
  for (let i = 0; i < printing.piece.length; i++) {
    const p = printing.piece[i], home = surface[p - 1], o = 3 * i;
    const pos = [pose.pos[o], pose.pos[o + 1], pose.pos[o + 2]], n = [pose.normal[o], pose.normal[o + 1], pose.normal[o + 2]];
    if (pos.join() !== home.join()) why.push(`sticker ${i + 1} of piece ${p} is at ${pos}, home is ${home}`);
    const axis = n.findIndex((v) => v !== 0);
    if (n[axis] !== Math.sign(home[axis]) || Math.abs(home[axis]) !== 3) why.push(`sticker ${i + 1} of piece ${p} faces ${n}, which is not outward at ${home}`);
    if (p === lastPiece && axis <= lastAxis) why.push(`sticker ${i + 1} of piece ${p} is not on the next face in x, y, z order`);
    lastPiece = p;
    lastAxis = axis;
  }
  return why;
}

test("root month 1980-01: the root pose is the identity pose of the print, every piece home, every sticker outward", () => {
  assert.equal(graph.nodes[0].year * 100 + graph.nodes[0].month, 198001);
  assert.deepEqual(start.node, { ...start.node, year: 1980, month: 1 });
  assert.equal(start.node.hash, graph.nodes[0].hash);
  assert.deepEqual(unsolved(start.printing, start.pose), []);
  assert.equal(start.printing.piece.length, 294);
  assert.equal(new Set(start.printing.piece).size, 218);
});

/**
 * Home face of every sticker, derived from the print alone (not from the pose under test): the stickers of piece p are numbered in
 * the order of the x, y, z faces of its home cell (the p-th cell of the surface), each facing outward on that axis.
 */
function independentHomes(printing) {
  const seen = new Map();
  return printing.piece.map((p) => {
    const home = surface[p - 1], k = seen.get(p) ?? 0;
    seen.set(p, k + 1);
    const axis = [0, 1, 2].filter((a) => Math.abs(home[a]) === 3)[k];
    const normal = [0, 0, 0];
    normal[axis] = Math.sign(home[axis]);
    return homeFaceOfNormal(normal);
  });
}
/** The faces of a pose (by the normal the stickers face now): the home colors found on each, and which faces are not one color. */
function faceColors(printing, pose) {
  const homes = independentHomes(printing), faces = new Map();
  for (let i = 0; i < 294; i++) {
    const o = 3 * i, key = `${pose.normal[o]},${pose.normal[o + 1]},${pose.normal[o + 2]}`;
    (faces.get(key) ?? faces.set(key, []).get(key)).push(i);
  }
  const mixed = [...faces].filter(([, ids]) => new Set(ids.map((i) => homes[i])).size !== 1).map(([key]) => key);
  return { homes, faces, mixed };
}

test("root month 1980-01: all 6 faces show one color, the front face is white in the Rubik-Tint scheme, and the front shows January 2019", () => {
  const scheme = SCHEMES.find((s) => s.id === "rubik-tint");
  const { homes, faces, mixed } = faceColors(start.printing, start.pose);
  assert.equal(faces.size, 6);
  assert.deepEqual(mixed, [], "every face shows one home color");
  const tints = new Map();
  for (const [key, ids] of faces) {
    assert.equal(ids.length, 49, `face ${key} has 49 stickers`);
    // The one color of the face is the home color of that face (solved), not any other.
    assert.equal(homes[ids[0]], homeFaceOfNormal(key.split(",").map(Number)), `face ${key} shows its own color`);
    // The ground the viewer paints: the face tint (weekdays, blanks) or its darkened weekend ground (red class), nothing else.
    const grounds = new Set(ids.map((i) => { const s = schemeForHome(scheme, homes[i]); return start.printing.ink[i] === "red" ? s.weekendFill : s.dayFill; }));
    assert.ok(grounds.size <= 2, `face ${key} has at most the tint and its weekend ground`);
    tints.set(key, RUBIK_TINTS[homes[ids[0]]]);
  }
  assert.equal(new Set(tints.values()).size, 6, "six different face colors");
  assert.equal(tints.get("0,0,1"), "#ffffff", "front face: Rubik-Tint white");
  assert.equal(schemeForHome(scheme, homes[faces.get("0,0,1")[0]]).dayFill, "#ffffff");
  assert.deepEqual(frontFailures(start.printing, start.pose, table.displays[0].cells), [], "the front shows the January 1980 board");
  // The independent homes agree with the library's classification of the root pose (identity pose of the print).
  assert.deepEqual(homes, homeFacesOf(start.pose));
});

test("the face-color check fails for the pose of 1980-02, a quarter turn and a scrambled root", () => {
  assert.notDeepEqual(faceColors(start.printing, poses[1]).mixed, [], "1980-02");
  assert.notDeepEqual(faceColors(start.printing, applyMoves(start.pose, [[1, 1]])).mixed, [], "one quarter turn");
  const scrambled = applyMoves(start.pose, graph.edges[2].moves);
  assert.notDeepEqual(faceColors(start.printing, scrambled).mixed, [], "scrambled");
});

test("the solved check is not trivially true: one quarter turn, or one sticker turned to another face, is not the solved cube", () => {
  assert.notDeepEqual(unsolved(start.printing, applyMoves(start.pose, [[1, 1]])), []);
  const bent = clonePose(start.pose);
  bent.normal.set([0, 0, 1], 0); // piece 1 lies at z = -3: this normal points into the cube
  assert.match(unsolved(start.printing, bent)[0], /sticker 1 of piece 1 faces 0,0,1/);
  const wrongFace = clonePose(start.pose);
  const j = start.printing.piece.findIndex((p, i) => start.pose.normal[3 * i + 2] === 1 && p > 100);
  wrongFace.normal.set([1, 0, 0], 3 * j);
  assert.notDeepEqual(unsolved(start.printing, wrongFace), []);
  const swapped = clonePose(start.pose); // stickers 1 and 2 of piece 1 exchange their faces: every sticker is still outward at its home cell
  swapped.normal.set(start.pose.normal.subarray(3, 6), 0);
  swapped.normal.set(start.pose.normal.subarray(0, 3), 3);
  assert.match(unsolved(start.printing, swapped)[0], /sticker 2 of piece 1 is not on the next face/);
  // Month 1980-02 (node 1) is not the solved cube.
  assert.notDeepEqual(unsolved(start.printing, poses[1]), []);
});

test("2019-01 is a normal chain state: it shows January 2019 (the same board as the root) but it is not the solved cube and its faces are mixed", () => {
  const k = FIRST_NODE_OF(2019, 1);
  assert.equal(k, 468);
  assert.deepEqual([graph.nodes[k].year, graph.nodes[k].month], [2019, 1]);
  assert.deepEqual(table.displays[k].cells, table.displays[0].cells, "January 1980 and January 2019 share one board");
  assert.deepEqual(frontFailures(start.printing, poses[k], table.displays[k].cells), [], "the front shows January 2019");
  assert.notDeepEqual(unsolved(start.printing, poses[k]), [], "not every piece is home");
  assert.notDeepEqual(faceColors(start.printing, poses[k]).mixed, [], "the faces are not one color each");
  assert.notEqual(graph.nodes[k].hash, graph.nodes[0].hash);
  // Only the back and the side faces differ from the root: the digest of 2019-01 is not that of the root, and the root is the only homogeneous state in the first year.
  const homogeneous = poses.map((p, i) => [i, faceColors(start.printing, p).mixed.length === 0]).filter(([, ok]) => ok).map(([i]) => i);
  assert.ok(homogeneous.includes(0) && !homogeneous.includes(k));
});
