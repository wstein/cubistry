// ---- chain structure ----

test("205 states, 204 edges, January 2019 to January 2036, one display per month", () => {
  assert.equal(STATES, 205);
  assert.equal(graph.nodes.length, 205);
  assert.equal(graph.edges.length, 204);
  assert.deepEqual(chainRange(graph), { first: { ...FIRST }, last: { ...LAST }, edges: 204 });
  assert.equal(table.months.length, 205);
  graph.nodes.forEach((n, k) => assert.deepEqual([n.year, n.month, n.display], [ymOf(k).year, ymOf(k).month, k + 1], `node ${k}`));
});

test("the end state of edge i is the start state of edge i+1: one replay, every node hash is reached, every edge starts at the previous node", () => {
  graph.edges.forEach((e, i) => {
    assert.deepEqual([e.from, e.to], [i, i + 1], `edge ${i} joins node ${i} to ${i + 1}`);
    assert.equal(stateDigest(start.printing, poses[i]), graph.nodes[i].hash, `start of edge ${i}`);
    assert.equal(stateDigest(start.printing, applyMoves(poses[i], e.moves)), graph.nodes[i + 1].hash, `end of edge ${i}`);
  });
  assert.equal(stateDigest(start.printing, poses[204]), graph.nodes[204].hash);
});

test("a swapped pair of edge words, a dropped move or a repeated edge breaks the chain at that edge", () => {
  const replayFrom = (k, moves) => stateDigest(start.printing, applyMoves(poses[k], moves));
  assert.notEqual(replayFrom(10, graph.edges[11].moves), graph.nodes[11].hash, "word of edge 11 does not belong to edge 10");
  assert.notEqual(replayFrom(10, graph.edges[10].moves.slice(1)), graph.nodes[11].hash, "dropped first move");
  assert.notEqual(replayFrom(11, graph.edges[10].moves), graph.nodes[12].hash, "edge 10 repeated at node 11");
  assert.throws(() => verifyChain(start.printing, start.pose, table, { nodes: graph.nodes, edges: graph.edges.map((e, i) => (i === 40 ? { ...e, moves: e.moves.slice(1) } : e)) }, best), /edge 40/);
});

// ---- the best-effort month ----

test("February 2026 is the one best-effort month: its front differs from its display in cell (7,1), the red 29, and no other month differs", () => {
  assert.deepEqual(best, [{ year: 2026, month: 2, wrong: [[7, 1]] }]);
  assert.deepEqual(BEST_EFFORT.wrong, [[7, 1]]);
  const k = (2026 - 2019) * 12 + 1;
  assert.deepEqual(ymOf(k), { year: 2026, month: 2 });
  const failures = poses.map((p, i) => frontFailures(start.printing, p, table.displays[i].cells));
  failures.forEach((f, i) => { if (i !== k) assert.equal(f.length, 0, `state ${i} (${ymOf(i).year}-${ymOf(i).month}) shows its display`); });
  assert.equal(failures[k].length, 1);
  const [miss] = failures[k];
  assert.deepEqual([miss.row, miss.column], [7, 1]);
  assert.equal(start.printing.text[miss.sticker - 1], "29");
  assert.equal(start.printing.ink[miss.sticker - 1], "red");
});

test("verifyChain accepts the chain only with the best-effort entry, and only for exactly that cell", () => {
  assert.equal(verifyChain(start.printing, start.pose, table, graph, best).edges.length, 204);
  assert.throws(() => verifyChain(start.printing, start.pose, table, graph), /edge 84: front differs from display 86 at 7,1/);
  assert.throws(() => verifyChain(start.printing, start.pose, table, graph, [{ ...best[0], wrong: [[7, 7]] }]), /edge 84: the cells that differ .* are \[7,1\], the best-effort entry lists \[7,7\]/);
  assert.throws(() => verifyChain(start.printing, start.pose, table, graph, [{ ...best[0], wrong: [[7, 1], [7, 7]] }]), /edge 84/);
  assert.throws(() => verifyChain(start.printing, start.pose, table, graph, [{ ...best[0], month: 3 }]), /edge 84: front differs from display 86/);
  assert.throws(() => verifyChain(start.printing, start.pose, table, graph, [{ year: 2018, month: 12, wrong: [[7, 1]] }]), /not an edge target/);
});

// ---- acceptance: the root month 2019-01 is the solved cube, front face white in Rubik-Tint ----

/** Home position of piece p (1..218): the p-th cell of the 7x7x7 surface in x, y, z order (x slowest), independent of the data. */
const surface = (() => {
  const out = [];
  for (let x = -3; x <= 3; x++) for (let y = -3; y <= 3; y++) for (let z = -3; z <= 3; z++) if (Math.max(Math.abs(x), Math.abs(y), Math.abs(z)) === 3) out.push([x, y, z]);
  return out;
})();
/**
 * Why a pose is not the solved cube of this print (empty: solved): a sticker off its piece's home cell, not on an outer face of
 * it, or on another face than its number says (the stickers of a piece are numbered in the order of the x, y, z faces).
 */
function unsolved(printing, pose) {
  const why = [];
  let lastPiece = 0, lastAxis = -1;
  for (let i = 0; i < printing.piece.length; i++) {
    const p = printing.piece[i], home = surface[p - 1], o = 3 * i;
    const pos = [pose.pos[o], pose.pos[o + 1], pose.pos[o + 2]], n = [pose.normal[o], pose.normal[o + 1], pose.normal[o + 2]];
    if (pos.join() !== home.join()) why.push(`sticker ${i + 1} of piece ${p} is at ${pos}, home is ${home}`);
    const axis = n.findIndex((v) => v !== 0);
    if (n[axis] !== Math.sign(home[axis]) || Math.abs(home[axis]) !== 3) why.push(`sticker ${i + 1} of piece ${p} faces ${n}, which is not outward at ${home}`);
    if (p === lastPiece && axis <= lastAxis) why.push(`sticker ${i + 1} of piece ${p} is not on the next face in x, y, z order`);
    lastPiece = p;
    lastAxis = axis;
  }
  return why;
}

test("root month 2019-01: the root pose is the identity pose of the print, every piece home, every sticker outward", () => {
  assert.equal(graph.nodes[0].year * 100 + graph.nodes[0].month, 201901);
  assert.equal(start.node.hash, graph.nodes[0].hash);
  assert.deepEqual(unsolved(start.printing, start.pose), []);
  assert.equal(start.printing.piece.length, 294);
  assert.equal(new Set(start.printing.piece).size, 218);
});

test("root month 2019-01: all 6 faces show one color, the front face is white in the Rubik-Tint scheme, and the front shows January 2019", () => {
  const scheme = SCHEMES.find((s) => s.id === "rubik-tint");
  const homes = homeFacesOf(start.pose);
  const faces = new Map();
  for (let i = 0; i < 294; i++) {
    const o = 3 * i, key = `${start.pose.normal[o]},${start.pose.normal[o + 1]},${start.pose.normal[o + 2]}`;
    (faces.get(key) ?? faces.set(key, []).get(key)).push(i);
  }
  assert.equal(faces.size, 6);
  const tints = new Map();
  for (const [key, ids] of faces) {
    assert.equal(ids.length, 49, `face ${key} has 49 stickers`);
    // Every sticker of the face has the home face of the face it lies on: one color per face.
    assert.deepEqual([...new Set(ids.map((i) => homes[i]))], [homeFaceOfNormal(key.split(",").map(Number))], `face ${key} is one color`);
    // The ground the viewer paints: the face tint (weekdays, blanks) or its darkened weekend ground (red class), nothing else.
    const grounds = new Set(ids.map((i) => { const s = schemeForHome(scheme, homes[i]); return start.printing.ink[i] === "red" ? s.weekendFill : s.dayFill; }));
    assert.ok(grounds.size <= 2, `face ${key} has at most the tint and its weekend ground`);
    tints.set(key, RUBIK_TINTS[homes[ids[0]]]);
  }
  assert.equal(new Set(tints.values()).size, 6, "six different face colors");
  assert.equal(tints.get("0,0,1"), "#ffffff", "front face: Rubik-Tint white");
  assert.equal(schemeForHome(scheme, homes[faces.get("0,0,1")[0]]).dayFill, "#ffffff");
  assert.deepEqual(frontFailures(start.printing, start.pose, table.displays[0].cells), [], "the front shows the January 2019 board");
});

test("the solved check is not trivially true: one quarter turn, or one sticker turned to another face, is not the solved cube", () => {
  assert.notDeepEqual(unsolved(start.printing, applyMoves(start.pose, [[1, 1]])), []);
  const bent = clonePose(start.pose);
  bent.normal.set([0, 0, 1], 0); // piece 1 lies at z = -3: this normal points into the cube
  assert.match(unsolved(start.printing, bent)[0], /sticker 1 of piece 1 faces 0,0,1/);
  const wrongFace = clonePose(start.pose);
  const j = start.printing.piece.findIndex((p, i) => start.pose.normal[3 * i + 2] === 1 && p > 100);
  wrongFace.normal.set([1, 0, 0], 3 * j);
  assert.notDeepEqual(unsolved(start.printing, wrongFace), []);
  const swapped = clonePose(start.pose); // stickers 1 and 2 of piece 1 exchange their faces: every sticker is still outward at its home cell
  swapped.normal.set(start.pose.normal.subarray(3, 6), 0);
  swapped.normal.set(start.pose.normal.subarray(0, 3), 3);
  assert.match(unsolved(start.printing, swapped)[0], /sticker 2 of piece 1 is not on the next face/);
  // Month 2019-02 (node 1) is not the solved cube.
  assert.notDeepEqual(unsolved(start.printing, poses[1]), []);
});
