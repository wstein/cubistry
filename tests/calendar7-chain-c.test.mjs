test("source.sha256 holds the pinned digests of the 9 chain evidence files, the 2 print files and the 673 snapshots", () => {
  const rows = readFileSync(`${DIR}/source.sha256`, "utf8").trimEnd().split("\n");
  assert.equal(rows.length, 2 + 9 + 673);
  assert.ok(rows.includes(`${PINNED["chain.moves.tsv"]}  research/calendar-7x7/row1-window-chain/evidence/chain-1980-2036/chain.moves.tsv`));
  assert.ok(rows.includes(`${PINNED.printing}  research/calendar-7x7/row1-window-chain/evidence/print-d/printing.tsv`));
  // A changed source digest, a changed snapshot digest and a missing snapshot each stop the check (source.sha256 is not in the manifest, so only the pins can fail).
  const mutate = (edit, expected) => {
    const dir = copy();
    writeFileSync(join(dir, "source.sha256"), edit(readFileSync(join(dir, "source.sha256"), "utf8")));
    assert.throws(() => check(dir), expected);
  };
  mutate((t) => t.replace(PINNED["months.tsv"], "0".repeat(64)), /source\.sha256 differs from the pin of months\.tsv/);
  mutate((t) => t.replace(/^[0-9a-f]{64}(  states\/state-077\.tsv)/m, `${"0".repeat(64)}$1`), /snapshots/);
  mutate((t) => t.split("\n").filter((l) => !l.endsWith("state-673.tsv")).join("\n"), /wrong number of entries/);
});

